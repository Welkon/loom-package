#!/usr/bin/env node
// Render the adapter surface: every *_port_t struct in the catalog, normalized.
// Usage: node tools/loom/ports.mjs [--out FILE] [--check] [--json]

import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const DEFAULT_OUT = "docs/ports.md";

function stripComments(text) {
  return text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");
}

function normalize(text) {
  return text.replace(/\s+/g, " ").trim();
}

function parseField(declaration) {
  const decl = normalize(declaration);
  if (!decl) return null;
  const fn = /^(.*?)\(\s*\*\s*([A-Za-z_]\w*)\s*\)\s*\((.*)\)$/.exec(decl);
  if (fn) {
    const [, ret, name, args] = fn;
    return {
      name,
      kind: "function",
      signature: `${normalize(ret)} (*${name})(${normalize(args)})`,
    };
  }
  const array = /^(.+?)\s*\*?\s*([A-Za-z_]\w*)\s*\[([^\]]*)\]$/.exec(decl);
  if (array) {
    const [, type, name, size] = array;
    return {
      name,
      kind: "array",
      signature: `${normalize(type).replace(/\*\s*$/, "")} ${name}[${normalize(size)}]`,
    };
  }
  const last = /([A-Za-z_]\w*)$/.exec(decl);
  if (!last) return null;
  const type = decl.slice(0, last.index).trim();
  if (!type) return null;
  const separator = type.endsWith("*") ? "" : " ";
  return {name: last[1], kind: "value", signature: `${type}${separator}${last[1]}`};
}

function parsePortStructs(source) {
  const text = stripComments(source);
  const found = [];
  const structs = /typedef\s+struct\s*\{(?<body>[\s\S]*?)\}\s*(?<name>[A-Za-z_]\w*)\s*;/g;
  for (const match of text.matchAll(structs)) {
    const type = match.groups.name;
    if (!type.endsWith("_port_t")) continue;
    const fields = match.groups.body
      .split(";")
      .map(parseField)
      .filter(Boolean);
    found.push({type, fields});
  }
  return found;
}

function headerFiles(root, unit) {
  const directory = path.join(root, unit.path);
  let names = [];
  try {
    names = fs.readdirSync(directory);
  } catch {
    return [];
  }
  return names
    .filter(name => name.endsWith(".h"))
    .sort()
    .map(name => path.join(directory, name));
}

export function extractPorts(root) {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, "loom.json"), "utf8"));
  const units = [...manifest.units].sort((a, b) => a.id.localeCompare(b.id));
  const ports = [];
  const bare = [];
  for (const unit of units) {
    let count = 0;
    for (const file of headerFiles(root, unit)) {
      const source = fs.readFileSync(file, "utf8");
      for (const port of parsePortStructs(source)) {
        const functions = port.fields.filter(field => field.kind === "function");
        ports.push({
          unit: unit.id,
          kind: unit.kind,
          directory: unit.path,
          header: path.relative(root, file).split(path.sep).join("/"),
          type: port.type,
          fields: port.fields,
          functions: functions.length,
        });
        count += 1;
      }
    }
    if (count === 0) bare.push({id: unit.id, kind: unit.kind, directory: unit.path});
  }
  return {units, ports, bare};
}

function renderStruct(port) {
  const body = port.fields.map(field => `    ${field.signature};`).join("\n");
  return `typedef struct {\n${body}\n} ${port.type};`;
}

export function renderMarkdown(report) {
  const {units, ports, bare} = report;
  const drivers = units.filter(unit => unit.kind === "driver").length;
  const totalFunctions = ports.reduce((sum, port) => sum + port.functions, 0);
  const lines = [];
  lines.push("# Adapter surface");
  lines.push("");
  lines.push("Generated by `node tools/loom/ports.mjs`; do not edit.");
  lines.push("");
  lines.push(`Every driver reaches hardware through a \`*_port_t\` struct. The project owns one`);
  lines.push(`implementation per struct; the catalog owns none. \`context\` is opaque and passed`);
  lines.push(`back unchanged.`);
  lines.push("");
  lines.push(`${ports.length} port structs, ${totalFunctions} port functions, across ${drivers} drivers.`);
  lines.push("Operators have no port and need no adapter.");
  lines.push("");
  lines.push("| Unit | Port type | Functions | Header |");
  lines.push("| --- | --- | --- | --- |");
  for (const port of ports) {
    lines.push(`| [\`${port.unit}\`](../${port.directory}) | \`${port.type}\` | ${port.functions} | \`${port.header}\` |`);
  }
  lines.push("");
  for (const port of ports) {
    lines.push(`## ${port.unit}`);
    lines.push("");
    lines.push(`\`${port.header}\``);
    lines.push("");
    lines.push("```c");
    lines.push(renderStruct(port));
    lines.push("```");
    lines.push("");
  }
  if (bare.length) {
    lines.push("## Units without a port");
    lines.push("");
    lines.push(bare.map(unit => `\`${unit.id}\``).join(", "));
    lines.push("");
  }
  return lines.join("\n");
}

export function generate(root) {
  const report = extractPorts(root);
  return {report, text: renderMarkdown(report)};
}

function main() {
  const args = process.argv.slice(2);
  const option = name => {
    const index = args.indexOf(`--${name}`);
    return index >= 0 ? args[index + 1] : undefined;
  };
  const root = path.resolve(option("root") || process.cwd());
  const out = path.resolve(root, option("out") || DEFAULT_OUT);
  const {report, text} = generate(root);
  if (args.includes("--json")) {
    process.stdout.write(JSON.stringify(report, null, 2) + "\n");
    return;
  }
  if (args.includes("--check")) {
    if (!fs.existsSync(out)) {
      console.error(`ports check failed: ${path.relative(root, out)} is missing (run make ports)`);
      process.exit(1);
    }
    const current = fs.readFileSync(out, "utf8");
    if (current !== text) {
      console.error(`ports check failed: ${path.relative(root, out)} is stale (run make ports)`);
      process.exit(1);
    }
    console.log(`ports check: ok (${report.ports.length} port structs)`);
    return;
  }
  fs.mkdirSync(path.dirname(out), {recursive: true});
  fs.writeFileSync(out, text);
  console.log(`ports: ${path.relative(root, out)} (${report.ports.length} port structs)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
